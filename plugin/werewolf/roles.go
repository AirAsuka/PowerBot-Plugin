func (r role) isWolf() bool {
	switch r {
	case roleWolf, roleWolfKing, roleWhiteWolfKing, roleEvilKnight, roleWolfBeauty, roleNightmare, roleGargoyle, roleWolfWizard:
		return true
	default:
		return false
	}
}

func (r role) canExplode() bool {
	return r.isWolf() && r != roleEvilKnight && r != roleWolfBeauty && r != roleGargoyle
}
